import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { stringifyYaml } from '@redocly/openapi-core';
import { specPrefix } from './checks';
import { bundleSource, createSpecConfig } from './lint';
import { bundleFileName, findSources } from './sources';

const GENERATED_FILE = /^[a-z0-9-]+-service-v\d+\.yaml$/;
const HEADER = '# Generated by `npm run bundle:specs`. Do not edit; change the source instead.\n';

export interface BundleOutput {
    source: string;
    /** Path from the repo root, with forward slashes. */
    file: string;
    content: string;
}

export async function buildBundles(rootDir: string): Promise<BundleOutput[]> {
    const config = await createSpecConfig();
    const outputs: BundleOutput[] = [];
    for (const source of await findSources(rootDir)) {
        const { parsed, errors } = await bundleSource(rootDir, source, config);
        if (errors.length > 0) throw new Error(`${source.file} does not bundle: ${errors.join('; ')}`);
        const prefix = specPrefix(parsed);
        if (prefix === undefined) {
            throw new Error(`${source.file}: all paths need one /v<N> prefix to name the bundle.`);
        }
        const file = `specs/${bundleFileName(source.service, prefix)}`;
        const clash = outputs.find((output) => output.file === file);
        if (clash) throw new Error(`${source.file} and ${clash.source} would both write ${file}.`);
        outputs.push({
            source: source.file,
            file,
            content: `# Source: ${source.file}\n${HEADER}${stringifyYaml(parsed)}`
        });
    }
    return outputs;
}

/** Bundles left in specs/ by an earlier run whose source is gone. */
async function findOrphans(rootDir: string, outputs: BundleOutput[]): Promise<string[]> {
    const expected = new Set(outputs.map((output) => output.file));
    const names = await readdir(path.join(rootDir, 'specs')).catch(() => []);
    const orphans: string[] = [];
    for (const name of names.filter((n) => GENERATED_FILE.test(n))) {
        const file = `specs/${name}`;
        if (expected.has(file)) continue;
        const text = await readFile(path.join(rootDir, file), 'utf8');
        if (text.includes(HEADER)) orphans.push(file);
    }
    return orphans;
}

export async function writeBundles(rootDir: string): Promise<BundleOutput[]> {
    const outputs = await buildBundles(rootDir);
    await mkdir(path.join(rootDir, 'specs'), { recursive: true });
    for (const output of outputs) {
        await writeFile(path.join(rootDir, output.file), output.content);
    }
    for (const orphan of await findOrphans(rootDir, outputs)) {
        await rm(path.join(rootDir, orphan));
    }
    return outputs;
}

/** Returns what is wrong with the committed bundles; empty means they are current. */
export async function checkBundles(rootDir: string): Promise<string[]> {
    const outputs = await buildBundles(rootDir);
    const problems: string[] = [];
    for (const output of outputs) {
        const current = await readFile(path.join(rootDir, output.file), 'utf8').catch(() => undefined);
        if (current === undefined) problems.push(`${output.file} is missing.`);
        else if (current.replaceAll('\r\n', '\n') !== output.content) {
            problems.push(`${output.file} is stale.`);
        }
    }
    for (const orphan of await findOrphans(rootDir, outputs)) {
        problems.push(`${orphan} has no source any more.`);
    }
    return problems;
}
