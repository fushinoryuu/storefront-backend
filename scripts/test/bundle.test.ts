import { copyFile, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { checkSpec } from '../specs/checks';
import { buildBundles, checkBundles, writeBundles } from '../specs/bundle';
import { fixtureCopies } from './support';

const fx = fixtureCopies();

afterEach(() => fx.cleanup());

describe('buildBundles', () => {
  it('names each bundle after the service and its path prefix', async () => {
    const outputs = await buildBundles(await fx.copy());
    expect(outputs.map(({ file }) => file)).toEqual([
      'specs/demo-service-v0.yaml',
      'specs/demo-service-v2.yaml',
      'specs/demo-service-v1.yaml',
    ]);
  });

  it('produces standalone files with no reference to another file', async () => {
    for (const { content } of await buildBundles(await fx.copy())) {
      expect(content).not.toMatch(/\$ref: ['"]?[^#'"]/);
      expect(content).toContain('# Generated by `npm run bundle:specs`');
    }
  });

  it('rejects two sources that would write the same file', async () => {
    const dir = await fx.copy();
    await copyFile(
      path.join(dir, 'services/demo/openapi.yaml'),
      path.join(dir, 'services/demo/openapi-v3.yaml'),
    );
    await expect(buildBundles(dir)).rejects.toThrow(
      /would both write specs\/demo-service-v1\.yaml/,
    );
  });

  it.each([
    ['a path without a prefix', '/v1/things:', '/things:'],
    ['paths with two prefixes', '/v1/things/{thingId}:', '/v2/things/{thingId}:'],
  ])('rejects a source with %s, which cannot name its bundle', async (_name, from, to) => {
    const dir = await fx.edited('services/demo/openapi.yaml', (text) => text.replace(from, to));
    await expect(buildBundles(dir)).rejects.toThrow(
      'services/demo/openapi.yaml: all paths need one /v<N> prefix to name the bundle.',
    );
  });

  it('rejects a source that does not bundle', async () => {
    const dir = await fx.edited('services/demo/openapi.yaml', (text) =>
      text.replace('components/responses/NotFound', 'components/responses/Missing'),
    );
    await expect(buildBundles(dir)).rejects.toThrow(
      /^services\/demo\/openapi\.yaml does not bundle: .*resolve \$ref/,
    );
  });
});

describe('writeBundles and checkBundles', () => {
  it('writes bundles that pass the project rules and are then current', async () => {
    const dir = await fx.copy();
    await writeBundles(dir);
    expect((await readdir(path.join(dir, 'specs'))).sort()).toEqual([
      'demo-service-v0.yaml',
      'demo-service-v1.yaml',
      'demo-service-v2.yaml',
      'shared',
    ]);
    expect(await checkBundles(dir)).toEqual([]);
  });

  it('reports a bundle that is stale after a source changes', async () => {
    const dir = await fx.copy();
    await writeBundles(dir);
    const source = path.join(dir, 'services/demo/openapi.yaml');
    await writeFile(
      source,
      (await readFile(source, 'utf8')).replace('Get a thing', 'Fetch a thing'),
    );
    expect(await checkBundles(dir)).toEqual(['specs/demo-service-v1.yaml is stale.']);
  });

  it('reports a stale bundle after a shared file changes', async () => {
    const dir = await fx.copy();
    await writeBundles(dir);
    const shared = path.join(dir, 'specs/shared/components.yaml');
    await writeFile(shared, (await readFile(shared, 'utf8')).replace('Not found', 'Missing'));
    expect(await checkBundles(dir)).toContain('specs/demo-service-v1.yaml is stale.');
  });

  it('reports a missing bundle', async () => {
    const dir = await fx.copy();
    await writeBundles(dir);
    await rm(path.join(dir, 'specs/demo-service-v2.yaml'));
    expect(await checkBundles(dir)).toEqual(['specs/demo-service-v2.yaml is missing.']);
  });

  it('removes and reports a generated bundle whose source is gone, but not other files', async () => {
    const dir = await fx.copy();
    await writeBundles(dir);
    await rm(path.join(dir, 'services/demo/openapi-v2.yaml'));
    await writeFile(path.join(dir, 'specs/hand-written-service-v9.yaml'), 'openapi: 3.0.3\n');
    expect(await checkBundles(dir)).toEqual(['specs/demo-service-v2.yaml has no source any more.']);
    await writeBundles(dir);
    expect(await checkBundles(dir)).toEqual([]);
    expect(await readdir(path.join(dir, 'specs'))).toContain('hand-written-service-v9.yaml');
    expect(await readdir(path.join(dir, 'specs'))).not.toContain('demo-service-v2.yaml');
  });

  it('writes bundles that pass the project rules', async () => {
    const dir = await fx.copy();
    for (const output of await buildBundles(dir)) {
      const { parseYaml } = await import('@redocly/openapi-core');
      expect(checkSpec(parseYaml(output.content))).toEqual([]);
    }
  });
});
